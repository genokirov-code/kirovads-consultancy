/* === GTM EVENT HELPER === */
function gtmEvent(eventName, params = {}) {
  window.dataLayer = window.dataLayer || [];
  window.dataLayer.push({ event: eventName, ...params });
}

/* === LANGUAGE SYSTEM ===
   Every translated page has its own URL: /page.html (EN) and /bg/page.html (BG),
   linked with <link rel="alternate" hreflang>. The BG pages are generated by build.py
   from the data-bg attributes, so the language of a page comes from its URL.
   Pages without a BG version (privacy, terms) switch text in place as before. */
const SUPPORTED_LANGS = ['en', 'bg'];

function hasLanguageVersions() {
  return !!document.querySelector('link[rel="alternate"][hreflang="bg"]');
}

function getStoredLang() {
  try {
    const stored = localStorage.getItem('kirovads_lang');
    if (SUPPORTED_LANGS.includes(stored)) return stored;
  } catch (e) { /* storage blocked */ }
  return null;
}

function storeLang(lang) {
  try { localStorage.setItem('kirovads_lang', lang); } catch (e) { /* storage blocked */ }
}

function detectLanguage() {
  if (hasLanguageVersions()) return getPageLang();
  return getStoredLang() || 'en';
}

let currentLang = detectLanguage();

/* URL of this page in another language, from its hreflang link */
function getAlternateUrl(lang) {
  const link = document.querySelector(`link[rel="alternate"][hreflang="${lang}"]`);
  if (!link) return null;
  return new URL(link.getAttribute('href'), window.location.href).pathname + window.location.hash;
}

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;

  /* Update all translatable elements */
  document.querySelectorAll('[data-en]').forEach(el => {
    const text = el.getAttribute(`data-${lang}`);
    if (!text) return;
    /* If the data attribute contains HTML tags, use innerHTML */
    if (text.includes('<')) {
      el.innerHTML = text;
    } else if (el.children.length === 0) {
      el.textContent = text;
    } else {
      /* Element has child elements (e.g. buttons with icons) — update first text node */
      for (const node of el.childNodes) {
        if (node.nodeType === Node.TEXT_NODE && node.textContent.trim()) {
          node.textContent = text + ' ';
          break;
        }
      }
    }
    /* Also update placeholder attributes */
    if (el.hasAttribute('placeholder')) {
      const ph = el.getAttribute(`data-${lang}-placeholder`);
      if (ph) el.setAttribute('placeholder', ph);
    }
  });

  /* Update HTML lang attribute placeholders on inputs */
  document.querySelectorAll('[data-en-placeholder]').forEach(el => {
    const ph = el.getAttribute(`data-${lang}-placeholder`);
    if (ph) el.setAttribute('placeholder', ph);
  });

  /* Update lang toggle buttons */
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active',
      (btn.id === 'langEN' || btn.id === 'langEN_m') ? lang === 'en' : lang === 'bg'
    );
  });

  storeLang(lang);
}

function setLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang) || lang === currentLang) return;
  gtmEvent('language_switch', { language: lang });
  storeLang(lang);
  const url = getAlternateUrl(lang);
  if (url) {
    window.location.href = url;
  } else {
    applyLanguage(lang);
    /* Nav and footer links point to the language root, so rebuild them */
    const active = document.querySelector('.nav__link.active');
    if (typeof initComponents === 'function') {
      const navEl = document.getElementById('nav-placeholder');
      const footerEl = document.getElementById('footer-placeholder');
      if (navEl) navEl.innerHTML = getNavHTML(active ? active.dataset.page : '');
      if (footerEl) footerEl.innerHTML = getFooterHTML();
      const fy = document.getElementById('footerYear');
      if (fy) fy.textContent = new Date().getFullYear();
      applyLanguage(lang);
    }
  }
}

/* === SCROLL ANIMATIONS === */
function initScrollAnimations() {
  const els = document.querySelectorAll('.fade-in');
  if (!els.length) return;
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(e => { if (e.isIntersecting) { e.target.classList.add('visible'); observer.unobserve(e.target); } });
  }, { threshold: 0.12 });
  els.forEach(el => observer.observe(el));
}

/* === FAQ ACCORDION === */
function initFAQ() {
  document.querySelectorAll('.faq-question').forEach(btn => {
    btn.addEventListener('click', () => {
      const item = btn.closest('.faq-item');
      const isOpen = item.classList.contains('open');
      /* Close all */
      document.querySelectorAll('.faq-item.open').forEach(i => i.classList.remove('open'));
      if (!isOpen) item.classList.add('open');
    });
  });
}

/* === BLOG POSTS ===
   blog/posts.json is generated by build.py from content/blog/*.md.
   Each post has an "en" and a "bg" block with its own title, excerpt and URL. */
function formatPostDate(iso, lang) {
  const d = new Date(iso + 'T00:00:00');
  return d.toLocaleDateString(lang === 'bg' ? 'bg-BG' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
}

function blogCardHTML(post, { dark = false, location = 'blog' } = {}) {
  const t = post[currentLang] || post.en;
  const href = getSiteRoot() + t.url.replace(/^\//, '');
  return `
    <article class="blog-card${dark ? ' blog-card--dark' : ''} fade-in">
      <a href="${href}" class="blog-card__img" tabindex="-1" aria-hidden="true">
        ${post.image
          ? `<img src="${getSiteRoot()}${post.image}" alt="" width="1600" height="900" loading="lazy">`
          : `<div class="img-placeholder${dark ? ' img-placeholder--dark' : ''}" style="min-height:180px">
               <span>${currentLang === 'bg' ? '[Снимка — очаква се]' : '[Image placeholder]'}</span>
             </div>`}
      </a>
      <div class="blog-card__body">
        <div class="blog-card__category">${t.category}</div>
        <h3 class="blog-card__title"><a href="${href}" style="color:inherit">${t.title}</a></h3>
        <p class="blog-card__excerpt">${t.excerpt}</p>
        <div style="display:flex;justify-content:space-between;align-items:center">
          <div class="blog-card__meta">
            <span>${formatPostDate(post.dateModified, currentLang)}</span>
            <span>·</span>
            <span>${t.readTime}</span>
          </div>
          <a href="${href}" class="blog-card__read-more"
             onclick="gtmEvent('blog_click',{post:'${post.id}',location:'${location}'})">${currentLang === 'bg' ? 'Прочетете →' : 'Read →'}</a>
        </div>
      </div>
    </article>`;
}

async function fetchPosts() {
  const res = await fetch(`${getSiteRoot()}blog/posts.json`);
  if (!res.ok) throw new Error('Failed to load posts');
  return (await res.json()).filter(p => p.published);
}

async function loadLatestPosts(count = 3) {
  const grid = document.getElementById('latestPostsGrid');
  if (!grid) return;
  const dark = grid.closest('.section--dark') !== null;

  try {
    const latest = (await fetchPosts()).slice(0, count);
    if (!latest.length) { grid.innerHTML = ''; return; }
    grid.innerHTML = latest.map(p => blogCardHTML(p, { dark, location: 'latest_section' })).join('');
    initScrollAnimations();
  } catch (e) {
    grid.innerHTML = `
      <div style="grid-column:1/-1;text-align:center;padding:2rem">
        <a href="${getRootPath()}blog/index.html" class="btn btn-outline-dark">${currentLang === 'bg' ? 'Към блога' : 'Visit the blog'}</a>
      </div>`;
  }
}

async function loadAllPosts() {
  const grid = document.getElementById('blogGrid');
  if (!grid) return;
  try {
    const posts = await fetchPosts();
    grid.innerHTML = posts.length
      ? posts.map(p => blogCardHTML(p, { location: 'blog_listing' })).join('')
      : `<p style="grid-column:1/-1;text-align:center;color:var(--gray-400)">${currentLang === 'bg' ? 'Очаквайте скоро.' : 'Articles coming soon.'}</p>`;
    initScrollAnimations();
  } catch (e) {
    grid.innerHTML = `<p style="grid-column:1/-1;text-align:center;color:var(--gray-400)">${currentLang === 'bg' ? 'Статиите не можаха да се заредят.' : 'Failed to load articles.'}</p>`;
  }
}

/* === CONTACT FORM === */
function initContactForm() {
  const form = document.getElementById('auditForm');
  if (!form) return;

  /* Preselect "I'm interested in" from ?interest=… links (pricing cards, CTAs) */
  const wanted = new URLSearchParams(window.location.search).get('interest');
  if (wanted) {
    const radio = form.querySelector(`input[name="interest"][value="${CSS.escape(wanted)}"]`);
    if (radio) radio.checked = true;
  }
  form.querySelectorAll('input[name="interest"]').forEach(r =>
    r.addEventListener('change', () => validateField(r)));

  /* Track form start (first interaction) */
  let formStarted = false;
  form.addEventListener('focusin', () => {
    if (!formStarted) {
      formStarted = true;
      gtmEvent('form_start', { form_id: 'audit_form' });
    }
  });

  /* Real-time validation */
  form.querySelectorAll('input[required], select[required], textarea[required]').forEach(field => {
    field.addEventListener('blur', () => validateField(field));
    field.addEventListener('input', () => { if (field.classList.contains('error')) validateField(field); });
  });

  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    if (!validateForm(form)) return;

    const submitBtn = form.querySelector('.form-submit-btn');
    const originalText = submitBtn.textContent;
    submitBtn.innerHTML = '<span class="loading-spinner"></span>';
    submitBtn.disabled = true;

    /* Collect form data */
    const data = new FormData(form);
    data.append('language', currentLang);
    const formObj = {};
    data.forEach((v, k) => { formObj[k] = v; });

    /* GTM form_submit event */
    gtmEvent('form_submit', {
      form_id: 'audit_form',
      interest: formObj.interest || '',
      industry: formObj.industry || '',
      budget: formObj.budget || '',
      platforms: formObj.platforms || '',
    });

    /* Formspree submission — replace YOUR_FORM_ID with actual Formspree ID */
    const FORMSPREE_ENDPOINT = 'https://formspree.io/f/mzdoagvn';

    try {
      const res = await fetch(FORMSPREE_ENDPOINT, {
        method: 'POST',
        body: data,
        headers: { 'Accept': 'application/json' },
      });

      if (res.ok) {
        window.location.href = (getRootPath ? getRootPath() : '') + 'thank-you.html';
      } else {
        throw new Error('Submission failed');
      }
    } catch (err) {
      /* Fallback: still redirect to thank-you (replace with real handler later) */
      window.location.href = (getRootPath ? getRootPath() : '') + 'thank-you.html';
    }
  });
}

function validateField(field) {
  const lang = currentLang;
  let valid = true;
  let msg = '';

  /* Radio groups: valid when any option in the group is chosen */
  if (field.type === 'radio') {
    const group = field.closest('.form-group');
    const errEl = group.querySelector(':scope > .form-error');
    valid = !!group.querySelector(`input[name="${field.name}"]:checked`);
    msg = lang === 'bg' ? 'Моля, изберете една от опциите.' : 'Please choose one option.';
    if (errEl) { errEl.textContent = valid ? '' : msg; errEl.style.display = valid ? 'none' : 'block'; }
    return valid;
  }

  const errEl = field.parentElement.querySelector('.form-error');
  if (field.required && !field.value.trim()) {
    valid = false;
    msg = lang === 'bg' ? 'Това поле е задължително.' : 'This field is required.';
  } else if (field.type === 'email' && field.value && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(field.value)) {
    valid = false;
    msg = lang === 'bg' ? 'Моля, въведи валиден имейл адрес.' : 'Please enter a valid email address.';
  }

  field.classList.toggle('error', !valid);
  if (errEl) { errEl.textContent = msg; errEl.style.display = valid ? 'none' : 'block'; }
  return valid;
}

function validateForm(form) {
  let valid = true;
  form.querySelectorAll('input[required], select[required], textarea[required]').forEach(field => {
    if (!validateField(field)) valid = false;
  });
  const consent = form.querySelector('#gdprConsent');
  if (consent && !consent.checked) {
    const errEl = consent.closest('.form-consent').querySelector('.form-error');
    const msg = currentLang === 'bg' ? 'Необходимо е вашето съгласие.' : 'Your consent is required.';
    if (errEl) { errEl.textContent = msg; errEl.style.display = 'block'; }
    valid = false;
  }
  return valid;
}

/* === COUNTER ANIMATION === */
function animateCounters() {
  document.querySelectorAll('[data-count]').forEach(el => {
    const target = parseFloat(el.getAttribute('data-count'));
    const suffix = el.getAttribute('data-suffix') || '';
    const prefix = el.getAttribute('data-prefix') || '';
    const duration = 1800;
    const start = performance.now();

    const step = (now) => {
      const progress = Math.min((now - start) / duration, 1);
      const eased = 1 - Math.pow(1 - progress, 3);
      const current = target * eased;
      el.textContent = prefix + (Number.isInteger(target) ? Math.round(current) : current.toFixed(1)) + suffix;
      if (progress < 1) requestAnimationFrame(step);
    };
    requestAnimationFrame(step);
  });
}

function initCounters() {
  const statsSection = document.querySelector('.stats');
  if (!statsSection) return;
  const observer = new IntersectionObserver((entries) => {
    if (entries[0].isIntersecting) { animateCounters(); observer.disconnect(); }
  }, { threshold: 0.4 });
  observer.observe(statsSection);
}

/* === ANCHOR LINKS (services.html#pricing etc.) ===
   Jump once the injected nav is in place, leaving room for the fixed nav. */
function scrollToHash() {
  if (!window.location.hash) return;
  const el = document.getElementById(decodeURIComponent(window.location.hash.slice(1)));
  if (!el) return;
  const nav = document.getElementById('mainNav');
  const top = el.getBoundingClientRect().top + window.scrollY - (nav ? nav.offsetHeight : 0);
  window.scrollTo({ top, behavior: 'instant' });
}

/* === INIT === */
document.addEventListener('DOMContentLoaded', () => {
  /* Apply the page language (from the URL) to page text and injected nav/footer */
  applyLanguage(currentLang);

  initScrollAnimations();
  initFAQ();
  initContactForm();
  initCounters();
  loadLatestPosts();
});
window.addEventListener('load', scrollToHash);
